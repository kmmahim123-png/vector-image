import sys
import json
import os
import zipfile
import color_separator

def make_separations_zip(svg_path, output_zip_path, width=800, height=800):
    with open(svg_path, 'r', encoding='utf-8') as f:
        svg_content = f.read()

    separations = color_separator.generate_screen_print_separations(svg_content, width, height)
    
    with zipfile.ZipFile(output_zip_path, 'w', zipfile.ZIP_DEFLATED) as zf:
        # Add a README for print shop technicians
        readme = f"""=======================================================
SCREEN PRINT SEPARATION FILMS - FREE VECTOR IMAGE PRO
=======================================================
Total Separations: {len(separations)} Films
Alignment: 4-Corner Target Crosshairs Included

INSTRUCTIONS FOR SCREEN EXPOSURE:
1. Print each SVG on high-density inkjet film transparency at 100% scale (no scaling).
2. Align all screens using the 4-corner crosshair registration marks.
3. Recommended emulsion: Dual-cure or photopolymer emulsion.
4. Recommended mesh counts:
   - Base White / Underbase: 110-156 mesh
   - Solid Spot Colors: 160-230 mesh
   - Fine Detail / Line Art: 230-305 mesh

Generated by Free Vector Image Studio (AI Precision Core)
"""
        zf.writestr("PRINT_SHOP_INSTRUCTIONS.txt", readme)

        for fname, fcontent in separations.items():
            zf.writestr(fname, fcontent)

    print(json.dumps({"success": True, "count": len(separations), "zip": output_zip_path}))

if __name__ == '__main__':
    if len(sys.argv) < 3:
        print(json.dumps({"error": "Usage: python zip_separations.py <svg_path> <output_zip_path> [w] [h]"}))
        sys.exit(1)
        
    w = int(sys.argv[3]) if len(sys.argv) > 3 else 800
    h = int(sys.argv[4]) if len(sys.argv) > 4 else 800
    make_separations_zip(sys.argv[1], sys.argv[2], w, h)
