/**
 * Free Vector Image - Ultra-High Quality Vector Exporter Suite
 * Eliminates white anti-aliasing gaps, guarantees responsive full-screen scaling,
 * and outputs production-grade SVG, EPS Level 3, AutoCAD DXF, and Vector PDF.
 */

(function (window) {
  'use strict';

  const VectorExporters = {
    /**
     * Converts RGB to Hex string
     */
    rgbToHex(r, g, b) {
      const h = (c) => ('0' + Math.max(0, Math.min(255, Math.round(c))).toString(16)).slice(-2);
      return `#${h(r)}${h(g)}${h(b)}`;
    },

    /**
     * 1. ULTRA-SMOOTH SVG GENERATOR
     * Fixes:
     * - Eliminates white anti-aliasing hairline cracks with matching color dilation stroke
     * - Responsive viewBox & 100% width/height so it never squishes or hugs the corner
     * - Clean standard SVG that opens gorgeously in all browsers and vector apps
     */
    generateSVG(td, opts = {}) {
      const mode = opts.mode || 'stroke_fill';
      const isWireframe = mode === 'wireframe';
      const w = td.width || 400;
      const h = td.height || 400;
      const round = (val) => Number(val.toFixed(2));

      // Dilation hairline stroke to completely eliminate browser anti-aliasing gaps
      const seamFixWidth = opts.seamFix !== false ? 0.45 : 0;
      const strokeWidth = mode === 'fill' ? seamFixWidth : (opts.strokeWidth || 0.85);

      let svg = `<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n`;
      svg += `<svg xmlns="http://www.w3.org/2000/svg" version="1.1" viewBox="0 0 ${w} ${h}" width="100%" height="100%" preserveAspectRatio="xMidYMid meet">\n`;
      svg += `  <!-- Generated by Free Vector Image (https://freevectorimage.io) -->\n`;
      svg += `  <defs>\n`;
      svg += `    <style>\n`;
      svg += `      svg { display: block; width: 100%; height: 100%; }\n`;
      svg += `      .fv-path { shape-rendering: geometricPrecision; text-rendering: geometricPrecision; }\n`;
      if (isWireframe) {
        svg += `      .fv-path path { fill: none !important; stroke: #06b6d4 !important; stroke-width: 1px !important; }\n`;
      }
      svg += `    </style>\n`;
      svg += `  </defs>\n`;

      td.layers.forEach((layer, layerIdx) => {
        const col = td.palette[layerIdx];
        if (!col || col.a === 0) return;
        if (opts.hiddenColors && opts.hiddenColors.has(layerIdx)) return;

        // Skip background if transparent requested
        if (opts.transparentBg && (layerIdx === 0 || (col.r > 240 && col.g > 240 && col.b > 240))) {
          return;
        }

        const hexColor = this.rgbToHex(col.r, col.g, col.b);
        const opacity = col.a !== undefined ? (col.a / 255).toFixed(3) : '1';

        svg += `  <g id="layer-${layerIdx}" class="fv-path"`;
        if (isWireframe) {
          svg += ` fill="none" stroke="#06b6d4" stroke-width="1"`;
        } else {
          svg += ` fill="${hexColor}"`;
          // Seam-free stroke rendering eliminates white cracks between adjacent polygons
          if (strokeWidth > 0) {
            svg += ` stroke="${hexColor}" stroke-width="${strokeWidth}" stroke-linejoin="round" stroke-linecap="round"`;
          } else {
            svg += ` stroke="none"`;
          }
        }

        if (opacity !== '1.000' && opacity !== '1') {
          svg += ` opacity="${opacity}"`;
        }
        svg += `>\n`;

        layer.forEach((pathObj) => {
          let d = '';
          const segments = pathObj.segments || [];
          segments.forEach((seg, si) => {
            if (si === 0) {
              d += `M ${round(seg.x1)} ${round(seg.y1)} `;
            }
            if (seg.type === 'L') {
              d += `L ${round(seg.x2)} ${round(seg.y2)} `;
            } else if (seg.type === 'Q') {
              d += `Q ${round(seg.x2)} ${round(seg.y2)} ${round(seg.x3)} ${round(seg.y3)} `;
            }
          });
          if (d.length > 0) {
            d += 'Z';
            svg += `    <path d="${d}" />\n`;
          }
        });

        svg += `  </g>\n`;
      });

      svg += `</svg>`;
      return svg;
    },

    /**
     * 2. POSTSCRIPT LEVEL 3 EPS GENERATOR
     */
    generateEPS(td, opts = {}) {
      const mode = opts.mode || 'stroke_fill';
      const strokeWidth = mode === 'fill' ? 0.35 : (opts.strokeWidth || 0.65);
      const w = Math.round(td.width || 400);
      const h = Math.round(td.height || 400);

      let eps = `%!PS-Adobe-3.0 EPSF-3.0\n`;
      eps += `%%BoundingBox: 0 0 ${w} ${h}\n`;
      eps += `%%HiResBoundingBox: 0.000 0.000 ${w}.000 ${h}.000\n`;
      eps += `%%Title: Free Vector Image Export\n`;
      eps += `%%Creator: Free Vector Image (https://freevectorimage.io)\n`;
      eps += `%%Pages: 1\n`;
      eps += `%%LanguageLevel: 3\n`;
      eps += `%%EndComments\n\n`;

      eps += `%%BeginProlog\n`;
      eps += `/m {moveto} bind def\n`;
      eps += `/l {lineto} bind def\n`;
      eps += `/c {curveto} bind def\n`;
      eps += `/cp {closepath} bind def\n`;
      eps += `/rgb {setrgbcolor} bind def\n`;
      eps += `%%EndProlog\n\n`;

      eps += `%%Page: 1 1\n`;
      eps += `gsave\n`;
      eps += `${strokeWidth} setlinewidth 1 setlinejoin 1 setlinecap\n\n`;

      td.layers.forEach((layer, layerIdx) => {
        const col = td.palette[layerIdx];
        if (!col || col.a === 0) return;
        if (opts.hiddenColors && opts.hiddenColors.has(layerIdx)) return;
        if (opts.transparentBg && (layerIdx === 0 || (col.r > 240 && col.g > 240 && col.b > 240))) return;

        const r = (col.r / 255).toFixed(4);
        const g = (col.g / 255).toFixed(4);
        const b = (col.b / 255).toFixed(4);

        eps += `% Layer ${layerIdx} - RGB(${col.r}, ${col.g}, ${col.b})\n`;
        eps += `${r} ${g} ${b} rgb\n`;

        layer.forEach((pathObj) => {
          const segments = pathObj.segments || [];
          if (segments.length === 0) return;

          eps += `newpath\n`;
          segments.forEach((seg, si) => {
            const y1 = (h - seg.y1).toFixed(2);
            if (si === 0) {
              eps += `${seg.x1.toFixed(2)} ${y1} m\n`;
            }

            if (seg.type === 'L') {
              const y2 = (h - seg.y2).toFixed(2);
              eps += `${seg.x2.toFixed(2)} ${y2} l\n`;
            } else if (seg.type === 'Q') {
              const cp1x = (seg.x1 + (2 / 3) * (seg.x2 - seg.x1)).toFixed(2);
              const cp1y = (h - (seg.y1 + (2 / 3) * (seg.y2 - seg.y1))).toFixed(2);
              const cp2x = (seg.x3 + (2 / 3) * (seg.x2 - seg.x3)).toFixed(2);
              const cp2y = (h - (seg.y3 + (2 / 3) * (seg.y2 - seg.y3))).toFixed(2);
              const endX = seg.x3.toFixed(2);
              const endY = (h - seg.y3).toFixed(2);

              eps += `${cp1x} ${cp1y} ${cp2x} ${cp2y} ${endX} ${endY} c\n`;
            }
          });

          eps += `cp\n`;
          eps += `gsave fill grestore stroke\n`;
        });
        eps += `\n`;
      });

      eps += `grestore\n`;
      eps += `showpage\n`;
      eps += `%%EOF\n`;

      return eps;
    },

    /**
     * 3. AUTOCAD DXF GENERATOR
     */
    generateDXF(td, opts = {}) {
      const h = td.height || 400;
      let dxf = `0\nSECTION\n2\nHEADER\n9\n$ACADVER\n1\nAC1009\n0\nENDSEC\n`;
      dxf += `0\nSECTION\n2\nTABLES\n0\nTABLE\n2\nLAYER\n70\n${td.layers.length}\n`;

      td.layers.forEach((_, idx) => {
        dxf += `0\nLAYER\n2\nLAYER_${idx}\n70\n0\n62\n${(idx % 7) + 1}\n6\nCONTINUOUS\n`;
      });
      dxf += `0\nENDTAB\n0\nENDSEC\n`;

      dxf += `0\nSECTION\n2\nENTITIES\n`;

      td.layers.forEach((layer, layerIdx) => {
        const col = td.palette[layerIdx];
        if (!col || col.a === 0) return;
        if (opts.hiddenColors && opts.hiddenColors.has(layerIdx)) return;
        if (opts.transparentBg && (layerIdx === 0 || (col.r > 240 && col.g > 240 && col.b > 240))) return;

        const layerName = `LAYER_${layerIdx}`;

        layer.forEach((pathObj) => {
          const segments = pathObj.segments || [];
          if (segments.length === 0) return;

          dxf += `0\nPOLYLINE\n8\n${layerName}\n66\n1\n70\n1\n`;

          segments.forEach((seg, si) => {
            const y1 = (h - seg.y1).toFixed(3);
            if (si === 0) {
              dxf += `0\nVERTEX\n8\n${layerName}\n10\n${seg.x1.toFixed(3)}\n20\n${y1}\n30\n0.0\n`;
            }

            if (seg.type === 'L') {
              const y2 = (h - seg.y2).toFixed(3);
              dxf += `0\nVERTEX\n8\n${layerName}\n10\n${seg.x2.toFixed(3)}\n20\n${y2}\n30\n0.0\n`;
            } else if (seg.type === 'Q') {
              const steps = 4;
              for (let t = 1; t <= steps; t++) {
                const u = t / steps;
                const inv = 1 - u;
                const px = inv * inv * seg.x1 + 2 * inv * u * seg.x2 + u * u * seg.x3;
                const py = h - (inv * inv * seg.y1 + 2 * inv * u * seg.y2 + u * u * seg.y3);
                dxf += `0\nVERTEX\n8\n${layerName}\n10\n${px.toFixed(3)}\n20\n${py.toFixed(3)}\n30\n0.0\n`;
              }
            }
          });

          dxf += `0\nSEQEND\n8\n${layerName}\n`;
        });
      });

      dxf += `0\nENDSEC\n0\nEOF\n`;
      return dxf;
    },

    /**
     * 4. VECTOR PDF GENERATOR
     */
    generatePDF(td, opts = {}) {
      const mode = opts.mode || 'stroke_fill';
      const strokeWidth = mode === 'fill' ? 0.35 : (opts.strokeWidth || 0.65);
      const w = Math.round(td.width || 400);
      const h = Math.round(td.height || 400);

      let stream = `q\n`;
      stream += `${strokeWidth} w 1 j 1 J\n`;

      td.layers.forEach((layer, layerIdx) => {
        const col = td.palette[layerIdx];
        if (!col || col.a === 0) return;
        if (opts.hiddenColors && opts.hiddenColors.has(layerIdx)) return;
        if (opts.transparentBg && (layerIdx === 0 || (col.r > 240 && col.g > 240 && col.b > 240))) return;

        const r = (col.r / 255).toFixed(4);
        const g = (col.g / 255).toFixed(4);
        const b = (col.b / 255).toFixed(4);

        stream += `${r} ${g} ${b} rg\n`;
        stream += `${r} ${g} ${b} RG\n`;

        layer.forEach((pathObj) => {
          const segments = pathObj.segments || [];
          if (segments.length === 0) return;

          segments.forEach((seg, si) => {
            const y1 = (h - seg.y1).toFixed(2);
            if (si === 0) {
              stream += `${seg.x1.toFixed(2)} ${y1} m\n`;
            }

            if (seg.type === 'L') {
              const y2 = (h - seg.y2).toFixed(2);
              stream += `${seg.x2.toFixed(2)} ${y2} l\n`;
            } else if (seg.type === 'Q') {
              const cp1x = (seg.x1 + (2 / 3) * (seg.x2 - seg.x1)).toFixed(2);
              const cp1y = (h - (seg.y1 + (2 / 3) * (seg.y2 - seg.y1))).toFixed(2);
              const cp2x = (seg.x3 + (2 / 3) * (seg.x2 - seg.x3)).toFixed(2);
              const cp2y = (h - (seg.y3 + (2 / 3) * (seg.y2 - seg.y3))).toFixed(2);
              const endX = seg.x3.toFixed(2);
              const endY = (h - seg.y3).toFixed(2);

              stream += `${cp1x} ${cp1y} ${cp2x} ${cp2y} ${endX} ${endY} c\n`;
            }
          });

          stream += `h\n`;
          stream += `B\n`;
        });
      });

      stream += `Q\n`;

      const streamBytes = new TextEncoder().encode(stream);
      const streamLen = streamBytes.length;

      const objects = [];
      const offsets = [];

      objects.push(`1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n`);
      objects.push(`2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n`);
      objects.push(`3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${w} ${h}] /Contents 4 0 R /Resources << >> >>\nendobj\n`);
      objects.push(`4 0 obj\n<< /Length ${streamLen} >>\nstream\n${stream}\nendstream\nendobj\n`);

      let pdfHeader = `%PDF-1.4\n%\xE2\xE3\xCF\xD3\n`;
      let currentOffset = pdfHeader.length;

      offsets.push(0);
      let body = '';
      objects.forEach((obj) => {
        offsets.push(currentOffset);
        body += obj;
        currentOffset += obj.length;
      });

      const xrefOffset = currentOffset;
      let xref = `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
      offsets.slice(1).forEach((off) => {
        xref += `${('0000000000' + off).slice(-10)} 00000 n \n`;
      });

      let trailer = `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;
      return pdfHeader + body + xref + trailer;
    },

    /**
     * File Download Helper
     */
    downloadFile(content, filename, mimeType) {
      const blob = typeof content === 'string' ? new Blob([content], { type: mimeType }) : content;
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      setTimeout(() => {
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
      }, 250);
    }
  };

  window.VectorExporters = VectorExporters;
})(window);
